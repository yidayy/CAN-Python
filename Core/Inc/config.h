#ifndef __CONFIG_H
#define __CONFIG_H

/* ============================================================================
 * config.h —— dianji 工程的"参数总闸"
 *
 * ⭐ 唯一原则：所有"以后可能要调的数字"，只在这个文件里出现一次。
 *   想改 PWM 频率、改占空比上限、换引脚、切换节点号，只改这里，
 *   不要去翻 motor.c / main.c —— 翻文件找参数是浪费时间的开始。
 * ==========================================================================*/

/* ---------------------------------------------------------------------------
 * 节点身份
 * 第一块板子 = 1，第二块板子 = 2。以后要 CAN 双向通信时，
 * 两块板子只差这一行（现在先放着，CAN 阶段直接用）。
 * -------------------------------------------------------------------------*/
#define NODE_ID                 1U

/* ---------------------------------------------------------------------------
 * PWM —— TIM1_CH1 / PA8
 *
 * 推导：72MHz(APB2) ÷ (TIM1_PSC+1) ÷ (TIM1_ARR+1)
 *       PSC = 0, ARR = 3599  →  72M ÷ 1 ÷ 3600 = 20.000 kHz
 *
 * 为什么是 20kHz：超出人耳听觉 (>18k) 不会有线圈啸叫；
 * 又不能太高 —— TB6612 的 MOSFET 有上升下降时间，开关损耗会抬头，
 * 20kHz 是这类小驱动器的舒适区。
 *
 * ⚠️ 这里的 MOTOR_TIM1_ARR 必须和 tim.c 里 `htim1.Init.Period` 完全一致
 *    （现在是 3599）。不一致的后果："代码算一套、硬件跑一套"，
 *    表现为最大转速莫名其妙对不上。
 * -------------------------------------------------------------------------*/
#define MOTOR_TIM1_ARR          3599U   /* = tim.c 里 htim1.Init.Period */

/* 占空比上限（千分比）。软保护，PID 输出再疯也不会超过它。*/
#define MOTOR_DUTY_MAX_PERMILLE 1000U   /* = 100% */

/* ---------------------------------------------------------------------------
 * 方向脚 —— TB6612 的 AIN1 / AIN2
 *
 *    AIN1=1 AIN2=0  →  正转
 *    AIN1=0 AIN2=1  →  反转
 *    AIN1=0 AIN2=0  →  自由停止（Hi-Z，电机惯性滑行）
 *    AIN1=1 AIN2=1  →  短路制动（MOSFET 全导通，电机被钉住）
 * -------------------------------------------------------------------------*/
#define MOTOR_DIR_PORT          GPIOB
#define MOTOR_DIR_PIN_AIN1      GPIO_PIN_0
#define MOTOR_DIR_PIN_AIN2      GPIO_PIN_1

/* ---------------------------------------------------------------------------
 * STBY —— TB6612 的待机脚
 *
 * ⚠️ 低电平 = 整片驱动器休眠，输出全关。
 * 忘了拉高它的现象：电机不转、量 VM 有 12V、量 AO1/AO2 没输出 ——
 * 而代码里 PWM 算得死死的"完全正确"，是新手最容易卡半天的坑之一。
 * ⭐ gpio.c 里 MX_GPIO_Init() 已在上电时把它置高，这里再兜一次。
 * -------------------------------------------------------------------------*/
#define MOTOR_STBY_PORT         GPIOB
#define MOTOR_STBY_PIN          GPIO_PIN_5

/* ---------------------------------------------------------------------------
 * 板载 LED —— PC13，低电平点亮（主流兼容板都一样）
 * 用"每档翻一次"告诉人：程序没跑飞、主循环还在转。
 * -------------------------------------------------------------------------*/
#define LED_PORT                GPIOC
#define LED_PIN                 GPIO_PIN_13

/* ---------------------------------------------------------------------------
 * 上电自检演示节奏
 * 档位序列：0 → +30 → +60 → +90 → -30 → -60 → -90 → 0 → 循环
 * -------------------------------------------------------------------------*/
#define MOTOR_DEMO_STEP_MS      1200U   /* 每档停留毫秒数 */
#define MOTOR_DEMO_P30          300     /* +30% */
#define MOTOR_DEMO_P60          600     /* +60% */
#define MOTOR_DEMO_P90          900     /* +90% */

#endif /* __CONFIG_H */
